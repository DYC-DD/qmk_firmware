// ===== 未能解決 =====
bool process_record_user(uint16_t keycode, keyrecord_t *record) {
  if (record->event.pressed) {
    if ((get_mods() & MOD_BIT(KC_RSFT)) && !(get_mods() & MOD_BIT(KC_LSFT))) {
      // 如果按下的是 A~Z
      if (keycode >= KC_A && keycode <= KC_Z) {
        char str[2] = { 'A' + (keycode - KC_A), '\0' };  // 半形大寫字母
        send_string(str); 
        return false;
      }
    }
  }
  return true;
}


